/// 程序内置的字体（系统里没有、又不能指望用户自己装的）：现在只有报纸风刊头的哥特体 UnifrakturCook Bold
/// （SIL OFL 1.1，许可证和来源见仓库 third_party/fonts/UnifrakturCook/，build_app.sh 拷进 Resources/fonts）。
///
/// 字体字节以 base64 嵌在这个源文件里：不用 SwiftPM resources —— Bundle.module 在 .app 里找不到资源包会直接崩。
/// 第一次用到时用 CTFontManagerCreateFontDescriptorsFromData 解出字体描述，按 PostScript 名记下；
/// 拼图排字按名字直接从描述建（CollageTypeset.resolveFont），不靠字体表。
/// 启动时另外把字节写成数据目录下的 fonts/UnifrakturCook-Bold.ttf、按文件注册进本进程的字体表（registerForProcess）：
/// 按名字找字体的地方（NSFont(name:)、SwiftUI Font.custom、属性字符串）也认得它。内存里的数据注册不进去
/// （CTFontManagerRegisterFontDescriptors 对内存描述返回错误，RegisterGraphicsFont 已废弃），所以要落一个文件。
enum CollageEmbeddedFonts {
    static let unifrakturCook = "UnifrakturCook-Bold"

    private static let fontData: Data? = Data(base64Encoded: unifrakturCookBase64, options: .ignoreUnknownCharacters)

    private static let descriptors: [String: CTFontDescriptor] = {
        var out: [String: CTFontDescriptor] = [:]
        guard let data = fontData,
              let descs = CTFontManagerCreateFontDescriptorsFromData(data as CFData) as? [CTFontDescriptor]
        else { return out }
        for d in descs {
            if let name = CTFontDescriptorCopyAttribute(d, kCTFontNameAttribute) as? String { out[name] = d }
        }
        return out
    }()

    /// 内置的这个名字的字体；不是内置的 = nil（走系统字体）。
    static func font(named name: String, size: CGFloat) -> CTFont? {
        guard name == unifrakturCook, let d = descriptors[name] else { return nil }
        return CTFontCreateWithFontDescriptor(d, size, nil)
    }

    /// 内置字体都解得出来（命令行字体自测用）。
    static var loadedNames: [String] { descriptors.keys.sorted() }

    /// 写成文件（内容一样就不重写）、注册进本进程的字体表（.process，不碰系统和别的程序）。启动时调一次。
    /// 写不了（只读的数据目录）就不注册：拼图排字照样从内嵌数据建，出图不受影响。返回是否注册上了。
    @discardableResult
    static func registerForProcess(in dataDir: URL) -> Bool {
        guard let data = fontData else { return false }
        let url = dataDir.appendingPathComponent("fonts/\(unifrakturCook).ttf")
        if (try? Data(contentsOf: url)) != data {
            try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            guard (try? data.write(to: url, options: .atomic)) != nil else { return false }
        }
        var error: Unmanaged<CFError>?
        if CTFontManagerRegisterFontsForURL(url as CFURL, .process, &error) { return true }
        // 已经注册过（同一个进程调了两次）也算注册上了。
        let code = error.map { CFErrorGetCode($0.takeRetainedValue()) }
        return code == CTFontManagerError.alreadyRegistered.rawValue
    }

